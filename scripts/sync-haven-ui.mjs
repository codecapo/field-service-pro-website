/* Vendors the real product design system out of the sibling app monorepo into
   this marketing site.

   Why vendor rather than depend on it: this site is its own git repo and builds
   on Vercel without the app checkout present, so a path/workspace dependency on
   @haven/core would work locally and fail in CI. Copying is the only thing that
   survives the build — and this script makes the copy repeatable so it doesn't
   quietly rot.

   Re-run after the app's design system changes:
       node scripts/sync-haven-ui.mjs

   Only presentational code is vendored. Anything that touches Dexie, Supabase,
   session or routing stays in the app where it belongs; the marketing mockups
   feed these components dummy data instead. */
import fs from "node:fs";
import path from "node:path";

const APP = "/Users/mayurkale/Development/field-service-pro/packages/core/src";
const DEST = path.join(process.cwd(), "components/haven");

if (!fs.existsSync(APP)) {
  console.error(
    `Cannot find the app monorepo at ${APP}\n` +
      `This script only runs on a machine with both repos checked out side by side.\n` +
      `The vendored output in components/haven is committed, so builds do not need it.`,
  );
  process.exit(1);
}

/* @haven/core/* -> relative paths, since we flatten into components/haven. */
function rewriteImports(code, fileDir) {
  return code.replace(/from "@haven\/core\/([^"]+)"/g, (_m, spec) => {
    const target = path.join(DEST, spec);
    let rel = path.relative(fileDir, target).replace(/\\/g, "/");
    if (!rel.startsWith(".")) rel = "./" + rel;
    return `from "${rel}"`;
  });
}

function copyTree(fromRel, toRel, only) {
  const from = path.join(APP, fromRel);
  const to = path.join(DEST, toRel);
  fs.mkdirSync(to, { recursive: true });
  let n = 0;
  for (const entry of fs.readdirSync(from, { withFileTypes: true })) {
    if (entry.isDirectory()) {
      n += copyTree(path.join(fromRel, entry.name), path.join(toRel, entry.name), only);
      continue;
    }
    if (!/\.tsx?$/.test(entry.name)) continue;
    if (/\.test\.tsx?$/.test(entry.name)) continue;
    /* Toast host — app runtime, not presentational. Skipping it keeps `sonner`
       and `next-themes` out of this site's dependency tree. */
    if (entry.name === "sonner.tsx") continue;
    if (only && !only.includes(entry.name)) continue;
    const code = fs.readFileSync(path.join(from, entry.name), "utf8");
    fs.writeFileSync(path.join(to, entry.name), rewriteImports(code, to));
    n++;
  }
  return n;
}

fs.rmSync(DEST, { recursive: true, force: true });
const counts = {
  "components/ui": copyTree("components/ui", "components/ui"),
  "components/patterns": copyTree("components/patterns", "components/patterns"),
  /* Only the `cn` helper — the rest of lib/ is Dexie, Supabase and sync. */
  "lib/utils": copyTree("lib", "lib", ["utils.ts"]),
};

fs.writeFileSync(
  path.join(DEST, "README.md"),
  `# Vendored product design system\n\n` +
    `Generated by \`scripts/sync-haven-ui.mjs\` — **do not edit by hand.**\n` +
    `Source of truth is \`packages/core/src\` in the field-service-pro monorepo.\n` +
    `Re-run the script to pull changes through.\n`,
);

for (const [k, v] of Object.entries(counts)) console.log(`${k.padEnd(22)} ${v} files`);
